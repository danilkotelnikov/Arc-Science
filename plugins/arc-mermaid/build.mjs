// Builds lib/client.js: one browser file from the ES modules of src/. Strips import and export lines; names are unique across modules.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const ORDER = ['colour', 'parse', 'layout', 'layout-seq', 'scene', 'gate', 'engine', 'audit', 'dom'];

function strip(src) {
  return src
    .replace(/^import\s[^;]*;\s*$/gm, '')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)/gm, '');
}

const parts = ORDER.map((n) => `// ---- ${n}\n` + strip(readFileSync(join(here, 'src', n + '.mjs'), 'utf8')));
const banner = `/**
 * arc-mermaid 0.1.0 (2026-11-09): the browser half. Generated by build.mjs from src/*.mjs; edit the sources, not this file.
 * Draws Mermaid flowchart, state and sequence diagrams in chat code blocks. The layout is chosen by the Molecullage gate.
 */
`;
const out = `${banner}window.__ModuleLoader__.load({
  id: 'arc-mermaid',
  factory: () => {
    'use strict';
${parts.join('\n').split('\n').map((l) => (l ? '    ' + l : l)).join('\n')}

    const api = { renderDiagram, search, parse, gate, createManager, toSvg, resolveLive, auditSvg, VERSION };
    return {
      name: 'arc-mermaid',
      inject: [],
      api,
      apply(ctx) {
        const manager = createManager({});
        ctx.effect(() => manager.start(), 'arc-mermaid: code blocks');
      },
    };
  },
});
`;
writeFileSync(join(here, 'lib', 'client.js'), out);
console.log('lib/client.js', out.length, 'bytes');


